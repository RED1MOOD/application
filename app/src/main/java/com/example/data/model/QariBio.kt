        fun findByName(name: String?): QariBio? {
            if (name == null) return null
            val normalizedSearch = name.trim()
                .replace("الشيخ ", "")
                .replace("د. ", "")
                .replace("فضيلة ", "")
                .replace("الدكتور ", "")
            
            // Try to match if target contains bio name, or bio name contains target
            val exactMatch = qariList.find { qari ->
                qari.name.contains(normalizedSearch) || 
                normalizedSearch.contains(qari.name) ||
                qari.fullName.contains(normalizedSearch) ||
                normalizedSearch.contains(qari.fullName)
            }
            if (exactMatch != null) return exactMatch
            
            // Try matching first words
            val searchFirstWord = normalizedSearch.split(" ").firstOrNull() ?: ""
            if (searchFirstWord.length > 2) {
                val partialMatch = qariList.find { qari ->
                    qari.name.contains(searchFirstWord) || searchFirstWord.contains(qari.name)
                }
                if (partialMatch != null) return partialMatch
            }
            return null
        }
